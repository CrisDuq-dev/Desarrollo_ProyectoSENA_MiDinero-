export function getArticleBySlug(slug) {
  return ARTICLES.find((a) => a.slug === slug) || null
}

export function getArticlesByCategory(category) {
  if (!category || category === 'Todos') return ARTICLES
  return ARTICLES.filter((a) => a.category === category)
}

/** Quita tildes y pasa a minúsculas para buscar mejor */
export function normalizeText(value) {
  return String(value || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
}

/**
 * Busca artículos por título, resumen, categoría, tags y contenido.
 * Sirve con palabras como: moneda, ahorro, cuota, transaccion, etc.
 */
export function searchArticles(list, query) {
  const q = normalizeText(query).trim()
  if (!q) return list

  const terms = q.split(/\s+/).filter(Boolean)

  return list.filter((article) => {
    const haystack = normalizeText(
      [
        article.title,
        article.summary,
        article.category,
        ...(article.tags || []),
        // un poco del contenido ayuda a coincidencias tipo "interés compuesto"
        String(article.content || '').slice(0, 1200),
      ].join(' ')
    )

    return terms.every((term) => haystack.includes(term))
  })
}

